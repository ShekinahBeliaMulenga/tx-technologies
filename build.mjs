// Assembles src/index.template.html + src/partials/*.html into index.html.
// No dependencies. Run:  node build.mjs
import { readFileSync, writeFileSync } from "node:fs";

const read = (p) => readFileSync(new URL(p, import.meta.url), "utf8");
const html = read("./src/index.template.html")
  .replace(/<!-- @css (.+?) -->/, (_, names) =>
    names.split(/\s+/).map((n) => `<link rel="stylesheet" href="css/${n}.css">`).join("\n  "))
  .replace(/^[ \t]*<!-- @include (\S+) -->/gm, (m, name) => {
    const indent = m.match(/^[ \t]*/)[0];
    return read(`./src/partials/${name}.html`).trimEnd().split("\n")
      .map((l) => (l.startsWith(indent) || !l ? l : indent + l)).join("\n");
  });

writeFileSync(new URL("./index.html", import.meta.url), html);

// Bundle the ES modules in js/ into one classic script (js/app.js) so the site also works
// when index.html is opened straight from disk (browsers block module scripts on file://).
const order = ["config", "dom", "services", "enquiry", "enquiry-bar", "nav", "lightbox", "main"];
const body = order.map((n) => `/* ${n}.js */\n` + read(`./js/${n}.js`)
  .replace(/^import[^;]*;\s*$/gm, "").replace(/^export (?=(const|function|async))/gm, "")).join("\n");
writeFileSync(new URL("./js/app.js", import.meta.url), `/* GENERATED by build.mjs from the other files in js/ - edit those, not this. */\n(() => {\n"use strict";\n${body}\n})();\n`);
console.log(`index.html built (${(html.length / 1024).toFixed(1)} KB)`);
